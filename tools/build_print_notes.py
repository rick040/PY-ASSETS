#!/usr/bin/env python3
"""Write docs/print-build-notes.md from elements.json and applications.json (PM-137 Phase 2 result)."""
import collections, json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def main():
    m = json.load(open(os.path.join(ROOT, "elements.json"), encoding="utf8"))
    els = {e["id"]: e for e in m["elements"]}
    new = [e for e in m["elements"] if e.get("origin") in ("print", "design")]
    apps = json.load(open(os.path.join(ROOT, "applications.json"), encoding="utf8"))["applications"]
    lv = collections.Counter(e["level"] for e in new)
    reb = [e for e in new if e["status"] == "rebuilt"]
    third = [e for e in new if "third-party" in e["tags"]]
    reused = {}
    for s in apps:
        for b in s["built_from"]:
            if b in els and els[b].get("origin") not in ("print", "design"):
                reused.setdefault(b, set()).add(s["id"])
    for e in new:
        for b in e["built_from"]:
            if b in els and els[b].get("origin") not in ("print", "design"):
                reused.setdefault(b, set()).add(e["id"])
    reused_el = {b for b in reused if els[b]["level"] != "tok"}
    reused_tok = {b for b in reused if els[b]["level"] == "tok"}
    nvar = sum(len(s["variants"]) for s in apps)
    o = []
    w = o.append
    w("# Print build notes (PM-137 Phase 2)\n")
    w("Generated by `tools/build_print_notes.py` from `elements.json` and `applications.json`.\n")
    w("## Counts\n")
    w("| What | Count |")
    w("|---|---|")
    w(f"| Applications | {len(apps)} ({nvar} versions: front and back or route and bestemming count as one application) |")
    w(f"| New atoms | {lv['atom']} |")
    w(f"| New components | {lv['comp']} |")
    w(f"| New products | {lv['prod']} |")
    w(f"| New elements in total | {len(new)} (rebuilt {len(reb)}, extracted {len(new) - len(reb)}, third-party reference {len(third)}) |")
    w(f"| Existing library elements reused (atoms, components, products) | {len(reused_el)} |")
    w(f"| Existing tokens referenced | {len(reused_tok)} |")
    w("")
    w("## Applications\n")
    w("| ID | Name | Type | Trim (mm) | Bleed (mm) | Status | Built from (existing) | Built from (new) |")
    w("|---|---|---|---|---|---|---|---|")
    for s in apps:
        ex = [b for b in s["built_from"] if b in els and els[b].get("origin") not in ("print", "design")]
        nw = [b for b in s["built_from"] if b in els and els[b].get("origin") in ("print", "design")]
        w(f"| `{s['id']}` | {s['name_nl']} | {s['type']} | {s['template']['trim_mm'][0]:g} x {s['template']['trim_mm'][1]:g} | {s['template']['bleed_mm']:g} | {s['status']} | {len(ex)} | {len(nw)} |")
    w("")
    w("## Reused existing elements\n")
    for b in sorted(reused_el):
        w(f"* `{b}`: used by " + ", ".join(f"`{x}`" for x in sorted(reused[b])))
    w("")
    w("## Rebuilt elements and why\n")
    w("`rebuilt` means part of the element is not taken straight from source paths: composed from library SVGs at new positions, text that is outlined in the source rebuilt as live Ubuntu, constructions.\n")
    w("| ID | Note |")
    w("|---|---|")
    for e in reb:
        w(f"| `{e['id']}` | " + (e["notes"] or "").replace("|", "/").replace("\n", " ")[:300] + " |")
    w("")
    w("## Applications with a rebuilt template\n")
    w("Every template is composed from library elements (positions measured on the print file) in official token colours; references are extracted. Application notes:\n")
    for s in apps:
        if s.get("notes"):
            w(f"* `{s['id']}`: {s['notes']}")
    w("")
    w("## Corrected copy in templates\n")
    for s in apps:
        for c in s.get("copy_corrections", []):
            w(f"* `{s['id']}`: \"{c['original']}\" to \"{c['corrected']}\"")
    w("")
    w("## Omitted from the references (hidden leftovers)\n")
    for s in apps:
        for c in s.get("omitted", []):
            w(f"* `{s['id']}`: {c}")
    w("")
    w("## Open points for decision\n")
    for t in (
        "Sticker cut contour corner radius (4.2 mm) is a proposal taken from the diefstal footer; the printer must confirm the contour shape.",
        "The asterisk after \"per dag\" on the Hofplein panel has no footnote text anywhere.",
        "Terms URL: handbook has `/nl/algemene-voorwaarden`, the Maashaven print has `/algemene-voorwaarden`. Template keeps the print URL as a variable.",
        "Brand spelling in running text: \"ParkingYou\" (form) versus \"parkingyou\" (logo, handbook). Not changed.",
        "Two reverse logos are in use in print (white dot on the A6 background, aqua dot on the card back). Both lockups exist (`py-comp-tagline-lockup`, `py-comp-tagline-lockup-reverse`).",
        "Inverted QR (white on navy) in Maashaven: test with the scanners in use before printing.",
        "Six print blues deviate from PY-Blauw (see `tokens.json` section `observed`); the printer files should be regenerated from the templates in the token blue.",
        "Third-party marks (payment brands, partner badges, GLOW) are reference only: source the official files.",
        "Light aqua (CMYK 54/0/14/0) has no token; confirm whether it becomes a brand colour.",
        "Terminal sticker sheet: contours of the info bubble and of the automaat storing sticker are proposals (no die line in the source); the printer must confirm all contours and the 3 mm bleed.",
        "Terminal sticker sheet: the pass card (scan pas) shows Philips Stadion branding and the scan pas sticker is location specific; swap the card group per location.",
        "New terminal sticker designs (kenteken invoeren, gele knop, ParkBee reservering): the yellow of the button, the sizes and Dutch only text are proposals; confirm against the real terminal.",
        "Terminal sticker sheet: three stickers appear twice on the sheet (druk 3 seconden, pijl links, automaatnummer). They are one application each; confirm they are meant to be identical.",
    ):
        w("* " + t)
    open(os.path.join(ROOT, "docs", "print-build-notes.md"), "w", encoding="utf8").write("\n".join(o) + "\n")
    print("docs/print-build-notes.md written")


if __name__ == "__main__":
    main()
