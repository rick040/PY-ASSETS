#!/usr/bin/env python3
"""Write docs/build-notes.md from elements.json and the Phase 1 inventory."""
import collections, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_all  # noqa: E402

NOT_BUILT = {
    "py-prod-portaal-luxe-spec": "p17 is an isometric 3D render (raster). The only vector on the page is footer, leader lines and the colour box, so there is nothing to extract.",
    "py-prod-rijstvliesbord-blank": "p50 is a raster render of a blank board with a text description; no artwork.",
}


def main():
    m = json.load(open(os.path.join(ROOT, "elements.json"), encoding="utf8"))
    els = m["elements"]
    inv = build_all.parse_inventory()
    built = {e["id"] for e in els}
    lv = collections.Counter(e["level"] for e in els)
    st = collections.Counter(e["status"] for e in els)
    out = []
    w = out.append
    w("# Build notes\n")
    w("Phase 2 result of the ParkingYou element extraction. Generated by `tools/build_notes.py` from `elements.json`.\n")
    w("## Counts\n")
    w("| Level | Elements | Rebuilt |")
    w("|---|---|---|")
    for l, n in (("tok", "Tokens"), ("atom", "Atoms"), ("comp", "Components"), ("prod", "Products")):
        rb = sum(1 for e in els if e["level"] == l and e["status"] == "rebuilt")
        w(f"| {n} | {lv[l]} | {rb} |")
    w(f"| Total | {sum(lv.values())} | {st['rebuilt']} |\n")
    third = [e["id"] for e in els if "third-party" in e["tags"]]
    w(f"Third-party reference marks ({len(third)}): " + ", ".join(f"`{i}`" for i in third) + "\n")

    w("## Decisions taken for the open Phase 1 questions\n")
    w("The Phase 1 questions were not answered one by one, so the recommended defaults were used. Change any of them and rebuild.\n")
    for s in ("Verloop: three measured stops (#1A3580 to 18 percent, #097BAE at 62 percent, #32B9CD at 100 percent) as a token.",
              "Colours: handbook 1.3 wins. Vector blue #1A3680 becomes #1A3580, logo black #010101 becomes PY-Zwart #1D1D1B, RAL swatches drawn on hardware become the brand blue and grey.",
              "Hoogtebalk lettering: typeface unidentified, kept as extracted outlines from p22.",
              "Reverse logos (white shape, navy ring, aqua dot) are separate atoms, tagged candidate. The stacked reverse logo is a construction (rebuilt), not a handbook drawing.",
              "Escape-plan symbols are tagged third-party, reference only.",
              "Arrows: only the 7 shown in the handbook; other directions are a suggested addition.",
              "Pictograms and figures are navy single-colour masters; white gap paths were turned into real holes (boolean difference). Recolours are not separate files.",
              "Spec sheets: portaal-standaard-spec (CAD, vector) and routebord-spec (side view) are products; the raster-only luxe spec and the rijstvliesbord render are not built.",
              "SVGs are in millimetres, true size where the handbook gives a dimension (dimensions_mm.basis), text is live Ubuntu. The handbook PDF is not stored in the repo.",
              "Open: whether the 2.1 lichtbak is single- or double-sided (the handbook does not say)."):
        w("* " + s)
    w("")
    w("## Inventory items without an element\n")
    missing = [i for i in inv if i not in built]
    w("| ID | Why |")
    w("|---|---|")
    for i in missing:
        w(f"| `{i}` | {NOT_BUILT.get(i, 'not built, see build log')} |")
    w("| 6.2 Folies technische specificaties | text and a third-party photo only; kept in notes, no artwork |")
    w("")

    w("## Rebuilt elements and why\n")
    w("`rebuilt` means part of the element is not taken straight from source paths. The usual reasons:\n")
    w("* **Gradients.** The blauw to aqua fills are shadings or 72 ppi images inside a clip path in the source. The clip outline (the exact shape) is kept, the fill is a real SVG gradient whose axis was measured from the rendered page.")
    w("* **Raster parts redrawn as vector** (hoogtebalk bands, chains and pendels, steel and plastic shading on posts, one pole fade).")
    w("* **Placeholders and constructions** (afbeeldingsmasker, stacked reverse logo).\n")
    w("| ID | Note |")
    w("|---|---|")
    for e in els:
        if e["status"] == "rebuilt":
            n = (e["notes"] or "").replace("|", "/").replace("\n", " ")
            w(f"| `{e['id']}` | {n[:260]} |")
    w("")

    w("## Colour deviations (handbook 1.3 wins)\n")
    w("| Found in the drawings | Used | Elements touched |")
    w("|---|---|---|")
    dev = collections.defaultdict(list)
    for e in els:
        for mm in re.finditer(r"\((#[0-9A-F]{6}) to (#[0-9A-F]{6})\)", e["notes"] or ""):
            dev[(mm.group(1), mm.group(2))].append(e["id"])
    for (a, b), ids in sorted(dev.items()):
        w(f"| `{a}` | `{b}` | {len(ids)} |")
    w("")
    w("`#082E7A` is the RAL 5002 swatch drawn on frames and hardware; normalising it makes some frames merge into the navy face (portals p18, p19, lichtbak frames). RAL values in the handbook are best match only.\n")

    w("## Open inconsistencies in the handbook\n")
    w("Not fixed in the artwork. The full list (27 items) is in `docs/phase1-inventory.md`, section 7. The ones that touch the assets:\n")
    for s in ("Logo weight: p6 and p7 say Medium, the outlines measure Regular for \"parking\". The outlines are what is in the SVGs.",
              "Hoogtebalk height is labelled 900 mm on p22 (three times); every other page and the geometry say 90 mm. The element notes use 90.",
              "Max doorrijhoogte: p15 and p18 show 2,4m on the RVV sign and 2,1m in the hoogtebalk lettering on the same drawing. Both are drawn as in the source.",
              "Bin sticker is written \"200x16,6mm\" (p24); the artwork measures 166 x 200 mm and is recorded as that.",
              "Portal drawings are not fully to one scale (the 520 mm and 200 mm dimensions do not follow the 600 mm bracket); products are scaled from the 600 mm plate height.",
              "The p12 display shows red and green dots; no VOL state is drawn anywhere (suggested addition).",
              "The white logo on lichtbak faces (white shape, navy ring, aqua dot) is not defined in 1.1; it is included as `-reverse` logo atoms."):
        w("* " + s)
    w("")
    w("## What to check in Illustrator\n")
    for s in ("Open the PDF. Each element should select as one group (marquee-select around it). If Illustrator opens elements as loose paths, select by marquee anyway: cells are spaced for that.",
              "Gradient fills may arrive as a clip group around a gradient rectangle (that is how PDF stores gradients). Release the clipping mask or use Object > Expand if you need a plain gradient-filled path. The SVGs in `svg/` use native SVG gradients.",
              "Labels are separate groups in 7 pt grey. Select one label, then Select > Same > Fill Color (or Same > Appearance) to select all labels and delete them before exporting.",
              "Text is live Ubuntu (Light, Regular, Medium, Bold). Install the fonts from `fonts/` first or Illustrator substitutes them. The logo wordmark is outlines.",
              "White artwork sits on a light grey tile (separate group) so it is visible; delete the tiles before export.",
              "Product pages are at one scale per page (stated in the subtitle). SVG files are 1:1 in millimetres where the handbook gives a dimension (`dimensions_mm.basis` = handbook scale), otherwise illustrative.",
              "Check the rebuilt elements against the handbook, especially gradient angles and the hoogtebalk bands."):
        w("* " + s)
    w("")
    w("## Suggested additions (not in the PDF)\n")
    for s in ("VOL and gesloten states of the display (only VRIJ is drawn).",
              "Remaining arrow directions as rotations of the existing arrows.",
              "Routebord width 800 (mentioned on p27, not drawn).",
              "Level bubbles for every digit and section letters as templates.",
              "Official files for RVV signs, Mastercard, Maestro, contactless and safety symbols."):
        w("* " + s)
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    open(os.path.join(ROOT, "docs", "build-notes.md"), "w", encoding="utf8").write("\n".join(out) + "\n")
    print("docs/build-notes.md written")


if __name__ == "__main__":
    main()
